# --------------------------------------------------------------------------
# 4. macros
# --------------------------------------------------------------------------
sp(name) = (sub = filter(r -> r[1] == name, rows); sub[1][3] / sub[4][3])
ppu(name) = 1e6 * filter(r -> r[1] == name, rows)[4][3] / N^2
open(joinpath(PAPER, "generated", "unwrap_numbers.tex"), "w") do io
    println(io, "% auto-generated by paper/scripts/studies/s13_unwrap.jl")
    println(io, "\\newcommand{\\UwCPU}{$(cpu)}")
    println(io, "\\newcommand{\\UwThreads}{$(nthr)}")
    @printf(io, "\\newcommand{\\UwSpeedFourth}{%.0f}\n", sp("fourth"))
    @printf(io, "\\newcommand{\\UwSpeedShowcase}{%.0f}\n", sp("showcase"))
    @printf(io, "\\newcommand{\\UwSpeedTurning}{%.0f}\n", sp("turning"))
    @printf(io, "\\newcommand{\\UwUsFourth}{%.1f}\n", ppu("fourth"))
    @printf(io, "\\newcommand{\\UwUsShowcase}{%.1f}\n", ppu("showcase"))
    @printf(io, "\\newcommand{\\UwUsTurning}{%.1f}\n", ppu("turning"))
end
println("s13 done: ", cpu, " x", nthr)
